"""Webapp experiment template: FastAPI page with upload -> gateway call -> result.

Generated by Wotan's experiment factory. Uses the gateway_client SDK - the
configured gateway contract and authentication are reused, never re-implemented.

Run: python webapp.py --port 8899
"""

from __future__ import annotations

import argparse
import asyncio
import logging
from pathlib import Path

from fastapi import FastAPI, File, Request, UploadFile
from fastapi.responses import HTMLResponse, JSONResponse

from wotan.gateway_client import chat, chat_with_document, chat_with_image

log = logging.getLogger("experiment.webapp")
logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")

app = FastAPI(title="Experiment: webapp template")
HERE = Path(__file__).parent


@app.get("/", response_class=HTMLResponse)
async def index() -> str:
    return (HERE / "static" / "index.html").read_text(encoding="utf-8")


@app.post("/api/analyze")
async def analyze(request: Request, file: UploadFile = File(...)) -> JSONResponse:
    """Upload a file, ask the gateway, return the answer."""
    try:
        data = await file.read()
        tmp = HERE / "output" / (file.filename or "upload.bin")
        tmp.parent.mkdir(parents=True, exist_ok=True)
        tmp.write_bytes(data)
        form = await request.form()
        prompt = str(form.get("prompt") or "Summarize this document.")
        name = (file.filename or "").lower()
        if name.endswith((".png", ".jpg", ".jpeg", ".gif", ".webp")):
            answer = await chat_with_image(prompt, tmp)
        elif name.endswith((".pdf", ".txt", ".md", ".csv")):
            answer = await chat_with_document(prompt, tmp)
        else:
            answer = await chat(f"{prompt}\n\nFile: {file.filename}")
        log.info("analyzed %s (%d bytes)", file.filename, len(data))
        return JSONResponse({"ok": True, "answer": answer})
    except Exception as exc:
        log.exception("analyze failed")
        return JSONResponse({"ok": False, "error": str(exc)}, status_code=500)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--port", type=int, default=8899)
    args = parser.parse_args()
    import uvicorn

    uvicorn.run(app, host="127.0.0.1", port=args.port)


if __name__ == "__main__":
    main()
